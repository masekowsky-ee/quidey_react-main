// Makes the built site an installable app (PWA): the build writes dist/sw.js, a service worker
// that keeps the app's files on the device, so Quidey starts fast and opens even offline.
// The manifest and icons are plain files in public/ (manifest.webmanifest, icons/).
//
// What the service worker does (and doesn't):
// - It stores only the app itself (index.html, the built JS/CSS/fonts, icons) — never API
//   answers, so no personal data ends up in its cache. /api and /socket.io and every other
//   origin (the production API) pass through untouched.
// - Pages (navigations) come from the network first, so a deploy is seen right away; only
//   without a connection the stored index.html is used.
// - Built files under /assets/ have a content hash in their name, so they come from the cache.
// - Each build has its own cache; the old one is deleted once the new service worker takes
//   over. It doesn't skip waiting: a running focus timer must not be reloaded underneath the
//   user. Pages are network-first anyway, so the newest app is loaded even before that.
import { createHash } from 'node:crypto';

// Files from public/ the app needs to start
export const PUBLIC_FILES = [
    '/',
    '/theme-init.js',
    '/quidey-logo.svg',
    '/manifest.webmanifest',
    '/icons/icon-192.png',
    '/icons/icon-512.png',
    '/icons/apple-touch-icon.png',
];

// The service worker's source for one build: `files` are the paths to store on install
export function serviceWorkerSource(files) {
    const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
    return `// Generated by pwa.js at build time — don't edit.
const CACHE = 'quidey-${version}';
const PRECACHE = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
    event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
    event.waitUntil(
        caches.keys()
            .then((keys) => Promise.all(keys.filter((key) => key.startsWith('quidey-') && key !== CACHE).map((key) => caches.delete(key))))
            .then(() => self.clients.claim()),
    );
});

// After a deploy, a missing /assets/ file comes back as the SPA's index.html: never store that
const storable = (response) => response.ok && !(response.headers.get('Content-Type') || '').includes('text/html');

self.addEventListener('fetch', (event) => {
    const request = event.request;
    if (request.method !== 'GET') return;
    const url = new URL(request.url);
    if (url.origin !== self.location.origin) return;
    if (url.pathname.startsWith('/api/') || url.pathname.startsWith('/socket.io/')) return;

    if (request.mode === 'navigate') {
        // every route of the SPA is the same index.html (stored under '/')
        event.respondWith(fetch(request).catch(() => caches.match('/', { cacheName: CACHE })));
        return;
    }
    if (url.pathname.startsWith('/assets/')) {
        event.respondWith(caches.match(request, { cacheName: CACHE }).then((hit) => hit || fetch(request).then((response) => {
            if (storable(response)) {
                const copy = response.clone();
                caches.open(CACHE).then((cache) => cache.put(request, copy));
            }
            return response;
        })));
        return;
    }
    // other files from public/: fresh when online, the stored copy when not
    event.respondWith(fetch(request).catch(() => caches.match(request, { cacheName: CACHE }).then((hit) => hit || Response.error())));
});
`;
}

// Vite plugin: adds sw.js to the build output, precaching every built file plus PUBLIC_FILES
export function pwa() {
    return {
        name: 'quidey-pwa',
        apply: 'build',
        generateBundle(_options, bundle) {
            const built = Object.keys(bundle)
                .filter((fileName) => fileName.startsWith('assets/'))
                .sort()
                .map((fileName) => `/${fileName}`);
            this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorkerSource([...PUBLIC_FILES, ...built]) });
        },
    };
}
